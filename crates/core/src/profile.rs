use crate::{normalize_relative, Error, Result};
use serde::{Deserialize, Serialize};
use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
};

pub const PROFILE_DIR: &str = ".stprofiles";
pub const STIGNORE: &str = ".stignore";

/// Escape Syncthing glob metacharacters in a literal path.
///
/// The backslash must be escaped first so it is not consumed twice.
pub fn escape_glob(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for c in value.chars() {
        if matches!(c, '[' | ']' | '{' | '}' | '*' | '?' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// Inverse of [`escape_glob`] for paths this project wrote.
pub fn unescape_glob(value: &str) -> Result<String> {
    let mut out = String::with_capacity(value.len());
    let mut chars = value.chars();
    while let Some(c) = chars.next() {
        if c == '\\' {
            let next = chars
                .next()
                .ok_or_else(|| Error::InvalidProfile("trailing escape".into()))?;
            out.push(next);
        } else {
            out.push(c);
        }
    }
    Ok(out)
}

/// Validate the profile file name. It becomes `.stprofiles/<device>.txt`.
pub fn validate_device(device: &str) -> Result<()> {
    if device.is_empty()
        || device.len() > 64
        || !device
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'))
        || device.starts_with('.')
    {
        return Err(Error::InvalidProfile(format!(
            "device name must be 1-64 characters of letters, digits, '.', '_' or '-': {device:?}"
        )));
    }
    Ok(())
}

pub fn profile_relative_path(device: &str) -> Result<String> {
    validate_device(device)?;
    Ok(format!("{PROFILE_DIR}/{device}.txt"))
}

/// The three-line `.stignore`. It is written once at bootstrap.
pub fn stignore_text(device: &str) -> Result<String> {
    validate_device(device)?;
    Ok(format!(
        "#include {PROFILE_DIR}/{device}.txt\n!/.stprofiles\n*\n"
    ))
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Profile {
    /// Generated comment lines at the top, including the leading `#`.
    pub header: Vec<String>,
    /// Hub base-ignore patterns, in order. Non-`!` lines are ignores.
    pub base_ignores: Vec<String>,
    /// Always-on paths, stored as logical relative paths.
    pub always_on: Vec<String>,
    /// Active project paths, stored as logical relative paths.
    pub active: Vec<String>,
}

impl Profile {
    pub fn new(
        device: &str,
        base_ignores: Vec<String>,
        always_on: Vec<String>,
        active: Vec<String>,
    ) -> Result<Self> {
        validate_device(device)?;
        Ok(Self {
            header: vec![
                format!("# Generated by photosync for {device}."),
                "# Do not edit; photosync rewrites this file.".to_string(),
            ],
            base_ignores,
            always_on: dedup_paths(always_on)?,
            active: dedup_paths(active)?,
        })
    }

    /// Parse a profile. `always_on` describes the paths the caller considers
    /// always-on so they are not mistaken for active projects.
    pub fn parse(text: &str, always_on: &[String]) -> Result<Self> {
        let always: Vec<String> = always_on
            .iter()
            .map(|p| normalize_relative(p))
            .collect::<Result<_>>()?;
        let mut header = Vec::new();
        let mut base_ignores = Vec::new();
        let mut active = Vec::new();
        let mut in_header = true;
        for raw in text.lines() {
            let line = raw.trim_end_matches('\r');
            if in_header && line.starts_with('#') {
                header.push(line.to_string());
                continue;
            }
            if in_header && line.trim().is_empty() {
                in_header = false;
                base_ignores.push(String::new());
                continue;
            }
            in_header = false;
            if let Some(rest) = line.strip_prefix("!/") {
                let path = unescape_glob(rest)?;
                let path = normalize_relative(&path)?;
                if !always.contains(&path) {
                    active.push(path);
                }
            } else {
                base_ignores.push(line.to_string());
            }
        }
        Ok(Self {
            header,
            base_ignores,
            always_on: always,
            active: dedup_paths(active)?,
        })
    }

    /// Render the exact bytes photosync writes to `.stprofiles/<device>.txt`.
    pub fn render(&self) -> String {
        let mut out = String::new();
        for line in &self.header {
            out.push_str(line.trim_end_matches('\r'));
            out.push('\n');
        }
        for line in &self.base_ignores {
            out.push_str(line.trim_end_matches('\r'));
            out.push('\n');
        }
        for path in &self.always_on {
            out.push_str("!/");
            out.push_str(&escape_glob(path));
            out.push('\n');
        }
        for path in &self.active {
            out.push_str("!/");
            out.push_str(&escape_glob(path));
            out.push('\n');
        }
        out
    }

    pub fn add_active(&mut self, path: &str) -> Result<()> {
        let path = normalize_relative(path)?;
        if !self.active.contains(&path) {
            self.active.push(path);
        }
        Ok(())
    }

    pub fn remove_active(&mut self, path: &str) -> Result<bool> {
        let path = normalize_relative(path)?;
        let before = self.active.len();
        self.active.retain(|p| p != &path);
        Ok(before != self.active.len())
    }
}

fn dedup_paths(paths: Vec<String>) -> Result<Vec<String>> {
    let mut out = Vec::new();
    for path in paths {
        let path = normalize_relative(&path)?;
        if !out.contains(&path) {
            out.push(path);
        }
    }
    Ok(out)
}

pub fn read_profile(path: &Path, always_on: &[String]) -> Result<Profile> {
    let text = fs::read_to_string(path)?;
    Profile::parse(&text, always_on)
}

/// Write a file with a same-directory temporary file and an atomic rename.
pub fn write_atomic(path: &Path, bytes: &[u8]) -> Result<()> {
    let parent = path
        .parent()
        .ok_or_else(|| Error::InvalidPath(format!("{} has no parent", path.display())))?;
    fs::create_dir_all(parent)?;
    let name = path
        .file_name()
        .and_then(|n| n.to_str())
        .ok_or_else(|| Error::InvalidPath(format!("invalid file name: {}", path.display())))?;
    let tmp = parent.join(format!(".{name}.tmp-{}", std::process::id()));
    let result = (|| {
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .open(&tmp)?;
        file.write_all(bytes)?;
        file.sync_all()?;
        drop(file);
        fs::rename(&tmp, path)?;
        Ok(())
    })();
    if result.is_err() {
        let _ = fs::remove_file(&tmp);
    }
    result
}

pub fn write_profile(path: &Path, profile: &Profile) -> Result<()> {
    write_atomic(path, profile.render().as_bytes())
}

/// Parse the three-line bootstrap file and return the device name it points at.
pub fn parse_stignore(text: &str) -> Option<String> {
    let mut lines = text
        .lines()
        .map(|l| l.trim_end_matches('\r').trim())
        .filter(|l| !l.is_empty());
    let first = lines.next()?;
    let device = first
        .strip_prefix("#include .stprofiles/")?
        .strip_suffix(".txt")?;
    if validate_device(device).is_err() {
        return None;
    }
    if lines.next()? != "!/.stprofiles" || lines.next()? != "*" {
        return None;
    }
    if lines.next().is_some() {
        return None;
    }
    Some(device.to_string())
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum BootstrapState {
    /// Neither file existed, or the profile was missing; both are now present.
    Created,
    /// Both files already matched.
    Present,
    /// The `.stignore` belongs to something else. It was not overwritten.
    Mismatch { existing: String },
}

/// Ensure the profile file exists before writing the `#include` that refers
/// to it. A missing include file stops the Syncthing folder, so order matters.
pub fn bootstrap(root: &Path, device: &str, profile: &Profile) -> Result<BootstrapState> {
    validate_device(device)?;
    let profile_path = root.join(profile_relative_path(device)?);
    write_profile(&profile_path, profile)?;
    let stignore = root.join(STIGNORE);
    let expected = stignore_text(device)?;
    if !stignore.exists() {
        write_atomic(&stignore, expected.as_bytes())?;
        return Ok(BootstrapState::Created);
    }
    let existing = fs::read_to_string(&stignore)?;
    if existing == expected || parse_stignore(&existing).as_deref() == Some(device) {
        Ok(BootstrapState::Present)
    } else {
        Ok(BootstrapState::Mismatch { existing })
    }
}

pub fn profile_path(root: &Path, device: &str) -> Result<PathBuf> {
    Ok(root.join(profile_relative_path(device)?))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn always() -> Vec<String> {
        vec!["inbox/PixelMob".to_string()]
    }

    #[test]
    fn escapes_every_metacharacter_and_round_trips() {
        for value in [
            "plain",
            "Trip [2024]",
            "a{b}c",
            "a*b?c",
            "back\\slash",
            "all [ ] { } * ? \\ together",
        ] {
            let escaped = escape_glob(value);
            assert!(!escaped.is_empty());
            assert_eq!(unescape_glob(&escaped).unwrap(), value);
        }
    }

    #[test]
    fn render_parse_round_trip_preserves_order_and_bytes() {
        let profile = Profile::new(
            "pixel",
            vec!["(?d).DS_Store".into(), "(?d)**/.DS_Store".into(), "".into()],
            always(),
            vec![
                "originals/Years/2024/2024.05.01 Coast".into(),
                "published/Years/2024/2024.05.01 Coast".into(),
                "originals/Projects/Trip [2024]".into(),
            ],
        )
        .unwrap();
        let rendered = profile.render();
        assert_eq!(
            Profile::parse(&rendered, &always()).unwrap().render(),
            rendered
        );
        let parsed = Profile::parse(&rendered, &always()).unwrap();
        assert_eq!(parsed.active.len(), 3);
        assert_eq!(parsed.always_on, always());
        assert_eq!(parsed.base_ignores[0], "(?d).DS_Store");
        assert!(!rendered.contains("!/.stprofiles"));
    }

    #[test]
    fn parses_crlf_and_keeps_later_comments() {
        let text = "# Generated\r\n# note\r\n(?d).DS_Store\r\n!/inbox/PixelMob\r\n# a later comment\r\n!/originals/Projects/A\r\n";
        let parsed = Profile::parse(text, &always()).unwrap();
        assert_eq!(parsed.header.len(), 2);
        assert_eq!(parsed.active, vec!["originals/Projects/A"]);
        assert_eq!(parsed.base_ignores[1], "# a later comment");
    }

    #[test]
    fn stignore_bootstrap_creates_profile_before_include() {
        let tmp = tempfile::tempdir().unwrap();
        let profile =
            Profile::new("pixel", vec!["(?d).DS_Store".into()], always(), vec![]).unwrap();
        let state = bootstrap(tmp.path(), "pixel", &profile).unwrap();
        assert_eq!(state, BootstrapState::Created);
        assert!(tmp.path().join(".stprofiles/pixel.txt").is_file());
        assert_eq!(
            fs::read_to_string(tmp.path().join(".stignore")).unwrap(),
            "#include .stprofiles/pixel.txt\n!/.stprofiles\n*\n"
        );
        assert_eq!(
            parse_stignore(&stignore_text("pixel").unwrap()).as_deref(),
            Some("pixel")
        );
    }

    #[test]
    fn bootstrap_never_overwrites_a_foreign_stignore() {
        let tmp = tempfile::tempdir().unwrap();
        fs::write(tmp.path().join(".stignore"), "custom\n").unwrap();
        let profile = Profile::new("pixel", vec![], always(), vec![]).unwrap();
        let state = bootstrap(tmp.path(), "pixel", &profile).unwrap();
        assert!(matches!(state, BootstrapState::Mismatch { .. }));
        assert_eq!(
            fs::read_to_string(tmp.path().join(".stignore")).unwrap(),
            "custom\n"
        );
    }

    #[test]
    fn rejects_unsafe_device_names() {
        for device in ["", "../x", "a/b", ".hidden", "has space"] {
            assert!(validate_device(device).is_err(), "{device}");
        }
        assert!(validate_device("pixel-mob_1").is_ok());
    }
}
